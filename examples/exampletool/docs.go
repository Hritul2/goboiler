package main

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	provenanceMarker = "<!-- example-provenance -->"
	markerPrefix     = "// example:"
)

var (
	directiveRe = regexp.MustCompile(`^<!-- example:([a-z]+)((?:\s+[a-z]+="[^"]*")*)\s*-->$`)
	attrRe      = regexp.MustCompile(`([a-z]+)="([^"]*)"`)
)

// source resolves directive paths: the overlay first (the example's own
// files), then the materialized tree (skeleton files and generated output).
type source struct {
	overlay string // examples/user/_overlay
	tree    string // materialized scratch tree
	sketch  string // examples/user
}

func (s source) read(rel string) (string, error) {
	if err := checkRel(rel); err != nil {
		return "", err
	}
	for _, root := range []string{s.overlay, s.tree} {
		b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err == nil {
			return string(b), nil
		}
		if !os.IsNotExist(err) {
			return "", err
		}
	}
	return "", fmt.Errorf("%s not found in the overlay or the materialized tree", rel)
}

func checkRel(rel string) error {
	if rel == "" || path.IsAbs(rel) || rel != path.Clean(rel) || rel == ".." || strings.HasPrefix(rel, "../") {
		return fmt.Errorf("invalid path %q (want a clean relative path)", rel)
	}
	return nil
}

func writeDocs(tree, tmplPath, outPath, module string) error {
	if module == "" {
		m, err := moduleFromGoMod("go.mod")
		if err != nil {
			return err
		}
		module = m
	}
	exDir := filepath.Dir(tmplPath)
	out, err := renderDocs(source{
		overlay: filepath.Join(exDir, "_overlay"),
		tree:    tree,
		sketch:  exDir,
	}, tmplPath, module)
	if err != nil {
		return err
	}
	return os.WriteFile(outPath, []byte(out), 0o644)
}

func moduleFromGoMod(file string) (string, error) {
	f, err := os.Open(file)
	if err != nil {
		return "", err
	}
	defer func() { _ = f.Close() }()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if rest, ok := strings.CutPrefix(sc.Text(), "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	return "", fmt.Errorf("no module line in %s", file)
}

// renderDocs renders the template. Line 1 of the template (the title) comes
// first, then the generated-file header and provenance block, then the rest of
// the template with its directives expanded.
func renderDocs(src source, tmplPath, module string) (string, error) {
	raw, err := os.ReadFile(tmplPath)
	if err != nil {
		return "", err
	}
	hash, err := sourceHash(src.sketch, module)
	if err != nil {
		return "", err
	}
	lines := strings.Split(strings.TrimRight(string(raw), "\n"), "\n")
	if len(lines) == 0 || !strings.HasPrefix(lines[0], "# ") {
		return "", fmt.Errorf("%s: line 1 must be the '# ' title", tmplPath)
	}

	var b strings.Builder
	b.WriteString(lines[0] + "\n")
	b.WriteString("<!-- Code generated by make example-docs from examples/user/EXAMPLE.md.tmpl. DO NOT EDIT. -->\n\n")
	b.WriteString(provenanceMarker + "\n")
	fmt.Fprintf(&b, "> Generated from [examples/user](../examples/user). Every block is compiled, linted and tested in CI (make example-check). Source hash: sha256:%s.\n", hash)

	for i, line := range lines[1:] {
		if strings.Contains(line, provenanceMarker) {
			return "", fmt.Errorf("%s:%d: the provenance marker is written by the generator", tmplPath, i+2)
		}
		if !strings.HasPrefix(line, "<!-- example:") {
			b.WriteString(line + "\n")
			continue
		}
		block, err := expand(src, line)
		if err != nil {
			return "", fmt.Errorf("%s:%d: %w", tmplPath, i+2, err)
		}
		b.WriteString(block)
	}
	return b.String(), nil
}

func expand(src source, line string) (string, error) {
	m := directiveRe.FindStringSubmatch(line)
	if m == nil {
		return "", fmt.Errorf("malformed directive: %s", line)
	}
	kind := m[1]
	attrs := map[string]string{}
	for _, a := range attrRe.FindAllStringSubmatch(m[2], -1) {
		attrs[a[1]] = a[2]
	}
	allowed := map[string][]string{
		"file":    {"path", "label"},
		"region":  {"path", "name", "label"},
		"excerpt": {"path", "from", "to", "label"},
		"sketch":  {"path"},
	}[kind]
	if allowed == nil {
		return "", fmt.Errorf("unknown directive %q", kind)
	}
	for k := range attrs {
		if !contains(allowed, k) {
			return "", fmt.Errorf("directive %q: unknown attribute %q", kind, k)
		}
	}
	p := attrs["path"]
	if p == "" {
		return "", fmt.Errorf("directive %q: path is required", kind)
	}

	switch kind {
	case "file":
		text, err := src.read(p)
		if err != nil {
			return "", err
		}
		return fence(label(attrs, p), p, stripMarkers(text), true), nil
	case "region":
		if attrs["name"] == "" {
			return "", fmt.Errorf("directive region: name is required")
		}
		text, err := src.read(p)
		if err != nil {
			return "", err
		}
		body, err := extractRegion(text, attrs["name"])
		if err != nil {
			return "", fmt.Errorf("%s: %w", p, err)
		}
		return fence(label(attrs, p), p, stripMarkers(body), true), nil
	case "excerpt":
		if attrs["from"] == "" || attrs["to"] == "" {
			return "", fmt.Errorf("directive excerpt: from and to are required")
		}
		text, err := src.read(p)
		if err != nil {
			return "", err
		}
		body, err := extractExcerpt(text, attrs["from"], attrs["to"])
		if err != nil {
			return "", fmt.Errorf("%s: %w", p, err)
		}
		return fence(label(attrs, p), p, body, true), nil
	default: // sketch
		if err := checkRel(p); err != nil {
			return "", err
		}
		b, err := os.ReadFile(filepath.Join(src.sketch, filepath.FromSlash(p)))
		if err != nil {
			return "", err
		}
		return fence("", "x.go", stripMarkers(string(b)), false), nil
	}
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

func label(attrs map[string]string, p string) string {
	if l := attrs["label"]; l != "" {
		return l
	}
	return p
}

// fence renders an optional bold header and a fenced code block, with the
// language taken from the extension of name.
func fence(header, name, body string, withHeader bool) string {
	var b strings.Builder
	if withHeader {
		fmt.Fprintf(&b, "**`%s`**\n\n", header)
	}
	fmt.Fprintf(&b, "```%s\n%s\n```\n", lang(name), strings.TrimRight(body, "\n"))
	return b.String()
}

func lang(name string) string {
	switch strings.ToLower(path.Ext(name)) {
	case ".go":
		return "go"
	case ".ts":
		return "ts"
	case ".tsx":
		return "tsx"
	case ".html":
		return "html"
	case ".sh":
		return "sh"
	case ".json":
		return "json"
	}
	return ""
}

func isMarker(line string) bool {
	return strings.HasPrefix(strings.TrimSpace(line), markerPrefix)
}

// stripMarkers removes every "// example:" marker line. gofmt keeps a blank
// line before an endregion marker, so when a removal would leave two blank
// lines in a row, one is dropped.
func stripMarkers(text string) string {
	var kept []string
	removed := false
	for _, l := range strings.Split(text, "\n") {
		if isMarker(l) {
			removed = true
			continue
		}
		if removed && strings.TrimSpace(l) == "" && len(kept) > 0 && strings.TrimSpace(kept[len(kept)-1]) == "" {
			removed = false
			continue
		}
		removed = false
		kept = append(kept, l)
	}
	return strings.Join(kept, "\n")
}

// extractRegion returns the lines between "// example:region NAME" and
// "// example:endregion NAME", without blank lines at either edge. A region
// name may be used several times in one file (for a snippet made of separate
// pieces); the pieces are joined with one blank line, in file order.
func extractRegion(text, name string) (string, error) {
	start, end := markerPrefix+"region "+name, markerPrefix+"endregion "+name
	var parts []string
	var cur []string
	open := false
	for _, l := range strings.Split(text, "\n") {
		switch strings.TrimSpace(l) {
		case start:
			if open {
				return "", fmt.Errorf("region %q starts again before it ends", name)
			}
			open, cur = true, nil
			continue
		case end:
			if !open {
				return "", fmt.Errorf("region %q ends before it starts", name)
			}
			open = false
			parts = append(parts, strings.Trim(strings.Join(cur, "\n"), "\n"))
			continue
		}
		if open {
			cur = append(cur, l)
		}
	}
	if open {
		return "", fmt.Errorf("region %q: end marker not found", name)
	}
	if len(parts) == 0 {
		return "", fmt.Errorf("region %q: start marker not found", name)
	}
	return strings.Join(parts, "\n\n"), nil
}

// extractExcerpt returns the lines from the first one containing from through
// the first one at or after it containing to, both inclusive.
func extractExcerpt(text, from, to string) (string, error) {
	lines := strings.Split(text, "\n")
	for i, l := range lines {
		if !strings.Contains(l, from) {
			continue
		}
		for j := i; j < len(lines); j++ {
			if strings.Contains(lines[j], to) {
				return strings.Join(lines[i:j+1], "\n"), nil
			}
		}
		return "", fmt.Errorf("excerpt end %q not found after line %d", to, i+1)
	}
	return "", fmt.Errorf("excerpt start %q not found", from)
}

// sourceHash is sha256 over every file under dir (the example), sorted by
// slash path, as path NUL content NUL. The module path is replaced with
// {{module}} first, so renaming the project (make init KEEP_EXAMPLES=1) keeps
// the hash. Returns the first 12 hex digits.
func sourceHash(dir, module string) (string, error) {
	var files []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || d.Name() == ".DS_Store" || !d.Type().IsRegular() {
			return nil
		}
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		files = append(files, filepath.ToSlash(rel))
		return nil
	})
	if err != nil {
		return "", err
	}
	sort.Strings(files)
	h := sha256.New()
	for _, rel := range files {
		b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
		if err != nil {
			return "", err
		}
		content := string(b)
		if module != "" {
			content = strings.ReplaceAll(content, module, "{{module}}")
		}
		h.Write([]byte(rel))
		h.Write([]byte{0})
		h.Write([]byte(content))
		h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil))[:12], nil
}
