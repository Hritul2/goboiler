func TestSourceHash(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "a.go", "import \"example.com/m/x\"\n")
	write(t, dir, "sub/b.txt", "b")
	write(t, dir, ".DS_Store", "junk")
	h1, err := sourceHash(dir, "example.com/m")
	if err != nil {
		t.Fatal(err)
	}
	if len(h1) != 12 {
		t.Fatalf("hash %q is not 12 hex digits", h1)
	}

	// Renaming the module (what make init does) must not change the hash.
	write(t, dir, "a.go", "import \"example.com/renamed/x\"\n")
	h2, _ := sourceHash(dir, "example.com/renamed")
	if h1 != h2 {
		t.Errorf("hash changed with the module path: %s vs %s", h1, h2)
	}

	// Any content change, or a new file, must change it.
	write(t, dir, "sub/b.txt", "c")
	h3, _ := sourceHash(dir, "example.com/renamed")
	if h3 == h2 {
		t.Error("hash did not change with file content")
	}
	write(t, dir, "new.txt", "")
	h4, _ := sourceHash(dir, "example.com/renamed")
	if h4 == h3 {
		t.Error("hash did not change with a new file")
	}
}

func TestRenderDocsErrors(t *testing.T) {
	cases := map[string]string{
		"unknown directive":   `<!-- example:bogus path="x" -->`,
		"malformed":           `<!-- example:file path=x -->`,
		"missing path attr":   `<!-- example:file -->`,
		"unknown attribute":   `<!-- example:file path="internal/a.go" colour="red" -->`,
		"missing file":        `<!-- example:file path="internal/nope.go" -->`,
		"missing region":      `<!-- example:region path="internal/a.go" name="nope" -->`,
		"missing region name": `<!-- example:region path="internal/a.go" -->`,
		"missing excerpt":     `<!-- example:excerpt path="gen/ts/v1/schemas.ts" from="nope" to="x" -->`,
		"missing sketch":      `<!-- example:sketch path="sketches/none.txt" -->`,
		"path escapes":        `<!-- example:file path="../go.mod" -->`,
		"absolute path":       `<!-- example:file path="/etc/passwd" -->`,
		"provenance marker":   `<!-- example-provenance -->`,
	}
	for name, line := range cases {
		t.Run(name, func(t *testing.T) {
			src, tmpl := newExample(t)
			write(t, filepath.Dir(tmpl), "EXAMPLE.md.tmpl", "# Example: x\n\n"+line+"\n")
			if _, err := renderDocs(src, tmpl, "m"); err == nil {
				t.Fatal("want an error")
			}
		})
	}
}

