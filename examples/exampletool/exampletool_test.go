func gitRepo(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not installed")
	}
	root := t.TempDir()
	if out, err := exec.Command("git", "-C", root, "init", "-q").CombinedOutput(); err != nil {
		t.Fatalf("git init: %v: %s", err, out)
	}
	return root
}

func TestMaterialize(t *testing.T) {
	root := gitRepo(t)
	write(t, root, ".gitignore", "secret.env\n")
	write(t, root, "go.mod", "module m\n")
	write(t, root, "internal/skel.go", "skeleton\n")
	write(t, root, "internal/replace.go", "skeleton version\n")
	write(t, root, "secret.env", "ignored")
	write(t, root, "examples/user/_overlay/internal/replace.go", "overlay version\n")
	write(t, root, "examples/user/_overlay/internal/new.go", "new\n")
	write(t, root, "examples/exampletool/main.go", "tool\n")
	// A tracked file that was then deleted from the working tree.
	write(t, root, "gone.txt", "x")
	if out, err := exec.Command("git", "-C", root, "add", "gone.txt").CombinedOutput(); err != nil {
		t.Fatalf("git add: %v: %s", err, out)
	}
	if err := os.Remove(filepath.Join(root, "gone.txt")); err != nil {
		t.Fatal(err)
	}

	dst := filepath.Join(t.TempDir(), "scratch")
	n, err := materialize(root, "examples/user/_overlay", dst, false)
	if err != nil {
		t.Fatal(err)
	}
	if n != 6 { // 4 project files (.gitignore, go.mod, 2 internal) + 2 overlay files
		t.Errorf("copied %d files, want 6", n)
	}
	read := func(rel string) string {
		b, err := os.ReadFile(filepath.Join(dst, rel))
		if err != nil {
			t.Fatalf("%s: %v", rel, err)
		}
		return string(b)
	}
	if read("internal/skel.go") != "skeleton\n" || read("internal/new.go") != "new\n" {
		t.Error("skeleton or overlay-only file missing")
	}
	if read("internal/replace.go") != "overlay version\n" {
		t.Error("overlay did not replace the skeleton file")
	}
	for _, rel := range []string{"secret.env", "examples", "gone.txt"} {
		if _, err := os.Stat(filepath.Join(dst, rel)); err == nil {
			t.Errorf("%s should not be in the scratch tree", rel)
		}
	}

	// A non-empty destination is refused unless -clean.
	if _, err := materialize(root, "examples/user/_overlay", dst, false); err == nil {
		t.Fatal("non-empty -dst should be refused")
	}
	write(t, dst, "stale.txt", "stale")
	if _, err := materialize(root, "examples/user/_overlay", dst, true); err != nil {
		t.Fatalf("-clean: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dst, "stale.txt")); err == nil {
		t.Error("-clean left a stale file behind")
	}
}

func TestMaterializeRefusesSourceAsDestination(t *testing.T) {
	root := gitRepo(t)
	write(t, root, "examples/user/_overlay/x.go", "x\n")
	if _, err := materialize(root, "examples/user/_overlay", root, true); err == nil {
		t.Fatal("-dst equal to the source must be refused")
	}
	if _, err := materialize(root, "examples/user/_overlay", filepath.Dir(root), true); err == nil {
		t.Fatal("-dst containing the source must be refused")
	}
	if _, err := os.Stat(filepath.Join(root, "examples/user/_overlay/x.go")); err != nil {
		t.Fatal("source was damaged")
	}
}

